// Builds console-recorder.js = extension/recorder/shape.js + src/console-main.js,
// so the console tool and the extension share one redaction implementation.
//   node tools/api-recorder/build.mjs          write it
//   node tools/api-recorder/build.mjs --check  fail if it's out of date (CI)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const shape = fs.readFileSync(path.join(here, "../../extension/recorder/shape.js"), "utf8");
const main = fs.readFileSync(path.join(here, "src/console-main.js"), "utf8");
const out = `/*!
 * Node API Recorder: console edition. GENERATED by tools/api-recorder/build.mjs
 * from extension/recorder/shape.js + tools/api-recorder/src/console-main.js. Don't edit by hand.
 *
 * Paste this whole file into the DevTools console on the site (F12 → Console).
 * Chrome may ask you to type "allow pasting" first. It records the page's API
 * calls as STRUCTURE ONLY (no message text, tokens or cookie values) and saves
 * the ones you mark to a JSON file. Nothing is sent anywhere.
 */
${shape}
${main}`;
const target = path.join(here, "console-recorder.js");
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (cur !== out) {
    console.error("console-recorder.js is out of date: run node tools/api-recorder/build.mjs");
    process.exit(1);
  }
  console.log("console-recorder.js is up to date");
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${out.length} bytes)`);
}
